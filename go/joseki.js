// 換方向：沿角的對角線翻轉（$T、$R 對調）
function mirrorPt(s) { const x = s.charCodeAt(0) - 97, y = s.charCodeAt(1) - 97; return String.fromCharCode(97 + 18 - y) + String.fromCharCode(97 + 18 - x); }
function mirror(j, idSuffix) {
  const swap = t => t.replace(/\$T/g, '\u0001').replace(/\$R/g, '$T').replace(/\u0001/g, '$R');
  return {
    id: j.id + idSuffix, level: j.level, name: j.name + '（換方向）', mirrored: true,
    intro: '同一個定石，換到另一個方向。定石是看「相對位置」，不是背座標，換個方向還能下對才算真的懂。',
    setup: { B: (j.setup.B || []).map(mirrorPt), W: (j.setup.W || []).map(mirrorPt) }, first: j.first,
    steps: j.steps.map(s => ({ m: mirrorPt(s.m), why: swap(s.why), alts: s.alts.map(a => ({ m: mirrorPt(a.m), g: a.g, t: swap(a.t) })) })),
    result: swap(j.result)
  };
}
